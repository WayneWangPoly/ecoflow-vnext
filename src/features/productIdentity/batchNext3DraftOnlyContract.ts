export type BatchNext3Candidate = typeof ECOFLOW_328_BATCH_NEXT3_DRAFT_TARGET.candidates[number];

export type BatchNext3QueueEvidence = {
  candidate: BatchNext3Candidate;
  row: BarcodeSurveyReconciliationRow;
  alreadyDrafted: boolean;
};

function normalized(value: string | null | undefined) {
  return (value ?? '').trim().toUpperCase();
}

export function validateBatchNext3Queue(
  rows: BarcodeSurveyReconciliationRow[],
  allowExistingDrafts: boolean,
): BatchNext3QueueEvidence[] {
  const target = ECOFLOW_328_BATCH_NEXT3_DRAFT_TARGET;
  const result = target.candidates.map((candidate) => {
    const row = rows.find((item) => item.surveyObservationId === candidate.surveyObservationId);
    if (!row) throw new Error(`${candidate.code}: frozen Survey observation is not present in the current queue.`);

    const alreadyDrafted = row.queueStatus === 'DRAFT_CREATED'
      && row.reconciliationStatus === 'DRAFTED'
      && Boolean(row.reconciliationId)
      && Boolean(row.productIdentityObservationId);

    if (row.queueStatus !== 'READY_TO_RECONCILE' && !(allowExistingDrafts && alreadyDrafted)) {
      throw new Error(`${candidate.code}: queue drifted to ${row.queueStatus}; stop.`);
    }
    if (row.commercialMatchCount !== 1 || row.commercialSkuId !== candidate.commercialSkuId) {
      throw new Error(`${candidate.code}: Commercial identity no longer matches the frozen unique target.`);
    }
    if (normalized(row.skuContext) !== candidate.code) {
      throw new Error(`${candidate.code}: Survey SKU context drifted to ${row.skuContext ?? 'NULL'}.`);
    }
    if (row.commercialName !== candidate.physicalName) {
      throw new Error(`${candidate.code}: canonical Commercial display name drifted.`);
    }
    if (row.cartonBarcode !== candidate.cartonBarcode) {
      throw new Error(`${candidate.code}: carton barcode drifted.`);
    }
    if (row.sleeveStatus !== 'SCANNED' || row.sleeveBarcode !== candidate.sleeveBarcode) {
      throw new Error(`${candidate.code}: frozen sleeve scan evidence drifted.`);
    }
    if (row.evidenceSource !== 'OBSERVED_NOW') {
      throw new Error(`${candidate.code}: direct physical evidence is no longer OBSERVED_NOW.`);
    }
    if (row.existingPhysicalSkuCode) {
      throw new Error(`${candidate.code}: barcode already has a published Physical SKU owner; stop.`);
    }
    if (!alreadyDrafted && (row.reconciliationId || row.productIdentityObservationId || row.reconciliationStatus)) {
      throw new Error(`${candidate.code}: reconciliation state is inconsistent with READY_TO_RECONCILE.`);
    }
    return { candidate, row, alreadyDrafted };
  });

  const distinctCommercial = new Set(result.map((item) => item.candidate.commercialSkuId));
  const distinctSurvey = new Set(result.map((item) => item.candidate.surveyObservationId));
  if (distinctCommercial.size !== target.candidates.length || distinctSurvey.size !== target.candidates.length) {
    throw new Error('Frozen Batch Next 3 scope is not ten distinct Commercial SKUs / Survey observations.');
  }
  return result;
}

